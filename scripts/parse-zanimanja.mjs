#!/usr/bin/env node
// Generiše frontend/src/data/zanimanja-fbih.ts iz zvaničnog abecednog spiska
// Klasifikacije zanimanja u FBiH (KZBiH-08 / ISCO-08, Federalni zavod za
// statistiku; Odluka o klasifikaciji zanimanja, Sl. novine FBiH 40/04 + dopune).
//
// Izvor: scripts/klasifikacija-zanimanja-fbih.xlsx (sheet "Abecedna tablica
// veza"), redovi [šifra "NNNN.NNN", naziv]. Šifra se čuva BEZ tačke (7 cifara)
// jer se tako upisuje u JS3100 obrazac.
//
// Pokretanje: node scripts/parse-zanimanja.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "scripts/klasifikacija-zanimanja-fbih.xlsx");
const OUT = path.join(ROOT, "frontend/src/data/zanimanja-fbih.ts");

const require = createRequire(path.join(ROOT, "frontend/package.json"));
const XLSX = require("xlsx");

// Zvanični dokument ima umiješana ćirilična slova-dvojnike (artefakt
// konverzije); normalizujemo ih u latinicu da pretraga i prikaz budu čisti.
const CIR_U_LAT = {
  "а": "a", "е": "e", "о": "o", "ј": "j", "с": "s", "р": "r", "х": "h",
  "и": "i", "у": "u", "н": "n", "т": "t", "к": "k", "м": "m", "д": "d",
  "в": "v", "г": "g", "л": "l", "п": "p", "з": "z", "б": "b", "ц": "c",
  "А": "A", "Е": "E", "О": "O", "Ј": "J", "С": "S", "Р": "R", "Х": "H",
  "И": "I", "У": "U", "Н": "N", "Т": "T", "К": "K", "М": "M", "Д": "D",
  "В": "V", "Г": "G", "Л": "L", "П": "P", "З": "Z", "Б": "B", "Ц": "C",
  "ć": "ć", "č": "č", "ш": "š", "ђ": "đ", "ж": "ž", "Ш": "Š", "Ђ": "Đ", "Ж": "Ž",
  "љ": "lj", "њ": "nj", "Љ": "Lj", "Њ": "Nj", "џ": "dž", "Џ": "Dž",
  "ч": "č", "Ч": "Č", "ћ": "ć", "Ћ": "Ć",
};
const uLatinicu = (s) =>
  [...String(s)].map((ch) => CIR_U_LAT[ch] ?? ch).join("");

const wb = XLSX.read(fs.readFileSync(SRC));
const sheet = wb.Sheets[wb.SheetNames[0]];
const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, raw: false });

const zanimanja = [];
const vidjene = new Set();
for (const r of rows) {
  if (!r || r.length < 2 || r[0] == null || r[1] == null) continue;
  const sifraRaw = String(r[0]).trim();
  if (!/^\d{4}\.\d{3}$/.test(sifraRaw)) continue; // zaglavlja i slova-sekcije
  const sifra = sifraRaw.replace(".", ""); // JS3100: 7 cifara bez tačke
  const naziv = uLatinicu(String(r[1])).replace(/\s+/g, " ").trim();
  if (!naziv) throw new Error(`Prazan naziv za šifru ${sifraRaw}`);
  if (/[Ѐ-ӿ]/.test(naziv)) {
    throw new Error(`Neprevedeno ćirilično slovo u: ${sifraRaw} ${naziv}`);
  }
  if (vidjene.has(sifra)) throw new Error(`Dupla šifra: ${sifraRaw}`);
  vidjene.add(sifra);
  zanimanja.push({ sifra, naziv });
}

if (zanimanja.length !== 4193) {
  throw new Error(`Očekivano 4193 zanimanja, parsirano ${zanimanja.length}`);
}

// abecedno po nazivu (bosanska abeceda kroz Intl collator)
const collator = new Intl.Collator("bs", { sensitivity: "base" });
zanimanja.sort((a, b) => collator.compare(a.naziv, b.naziv) || a.sifra.localeCompare(b.sifra));

const ts = `// Auto-generated by scripts/parse-zanimanja.mjs from
// scripts/klasifikacija-zanimanja-fbih.xlsx (Klasifikacija zanimanja u FBiH,
// KZBiH-08 / ISCO-08, abecedni spisak, Federalni zavod za statistiku).
// Do not edit by hand — re-run the parser to regenerate.
//
// Šifra je 7 cifara BEZ tačke (zvanični oblik "NNNN.NNN"), jer se tako
// upisuje u JS3100 obrazac (polje "Zanimanje, Šifra").

export type Zanimanje = {
  /** 7 cifara, npr. "4110001" (zvanično 4110.001) */
  sifra: string;
  naziv: string;
};

export const ZANIMANJA_FBIH: Zanimanje[] = ${JSON.stringify(zanimanja, null, 2)};
`;

fs.writeFileSync(OUT, ts, "utf8");
console.log(`Wrote ${OUT}`);
console.log(`Zanimanja: ${zanimanja.length}`);
